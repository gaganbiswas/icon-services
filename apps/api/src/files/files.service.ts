import { createHash, randomUUID } from 'node:crypto';

import { Inject, Injectable } from '@nestjs/common';
import type { StoredFileInfo } from '@icon/contracts';
import type { PrismaClient } from '@icon/database';

import { AppException } from '../common/app-exception.js';
import { PRISMA } from '../prisma/prisma.service.js';
import { sanitizeFileName, validateUpload } from './file-validation.js';
import { StorageService } from './storage.service.js';

export type Uploader = { kind: 'user'; userId: string } | { kind: 'customer'; customerId: string };

@Injectable()
export class FilesService {
  constructor(
    @Inject(PRISMA) private readonly prisma: PrismaClient,
    private readonly storage: StorageService,
  ) {}

  /** Validates, stores under a random key, and records the file. */
  async upload(
    organizationId: string,
    uploader: Uploader,
    buffer: Buffer,
    originalName: string | undefined,
  ): Promise<StoredFileInfo> {
    const { mimeType, extension } = await validateUpload(buffer);
    const id = randomUUID();
    const storageKey = `org/${organizationId}/uploads/${id}.${extension}`;
    await this.storage.put(storageKey, buffer, mimeType);
    const row = await this.prisma.storedFile.create({
      data: {
        organizationId,
        storageKey,
        originalName: sanitizeFileName(originalName),
        mimeType,
        sizeBytes: buffer.length,
        sha256: createHash('sha256').update(buffer).digest('hex'),
        classification: 'PERSONAL',
        uploadedByUserId: uploader.kind === 'user' ? uploader.userId : null,
        uploadedByCustomerId: uploader.kind === 'customer' ? uploader.customerId : null,
      },
    });
    return {
      id: row.id,
      originalName: row.originalName,
      mimeType: row.mimeType,
      sizeBytes: row.sizeBytes,
      createdAt: row.createdAt.toISOString(),
    };
  }

  /** Stores generated bytes (e.g. PDFs) — not user input, no sniffing. */
  async storeGenerated(
    organizationId: string,
    buffer: Buffer,
    originalName: string,
    mimeType: string,
    db: Pick<PrismaClient, 'storedFile'> = this.prisma,
  ): Promise<string> {
    const id = randomUUID();
    const storageKey = `org/${organizationId}/documents/${id}.pdf`;
    await this.storage.put(storageKey, buffer, mimeType);
    const row = await db.storedFile.create({
      data: {
        organizationId,
        storageKey,
        originalName,
        mimeType,
        sizeBytes: buffer.length,
        sha256: createHash('sha256').update(buffer).digest('hex'),
        classification: 'DOCUMENT',
      },
      select: { id: true },
    });
    return row.id;
  }

  /** Signed URL for a file already authorized by the caller. */
  async signedUrl(
    organizationId: string,
    fileId: string,
  ): Promise<{ url: string; expiresAt: string }> {
    const file = await this.prisma.storedFile.findFirst({
      where: { id: fileId, organizationId },
      select: { storageKey: true, originalName: true },
    });
    if (!file) {
      throw AppException.notFound('File');
    }
    const { url, expiresAt } = await this.storage.signedDownloadUrl(
      file.storageKey,
      file.originalName,
    );
    return { url, expiresAt: expiresAt.toISOString() };
  }

  /**
   * Checks files referenced in a request: same organization, uploaded by this
   * uploader, and not yet attached elsewhere (prevents attaching others' files).
   */
  async assertAttachable(
    organizationId: string,
    uploader: Uploader,
    fileIds: readonly string[],
  ): Promise<void> {
    if (fileIds.length === 0) return;
    const unique = [...new Set(fileIds)];
    const count = await this.prisma.storedFile.count({
      where: {
        id: { in: unique },
        organizationId,
        classification: 'PERSONAL',
        jobAttachments: { none: {} },
        ...(uploader.kind === 'user'
          ? { uploadedByUserId: { not: null } }
          : { uploadedByCustomerId: uploader.customerId }),
      },
    });
    if (count !== unique.length) {
      throw AppException.notFound('File');
    }
  }
}
